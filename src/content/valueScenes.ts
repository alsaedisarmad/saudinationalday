/**
 * مشاهد القيم الست («عزّنا بطبعنا»): لكل قيمة مشهد وتفاعل و«دلالة» موثّقة قصيرة.
 * - الكلمة والعبارة (word/phrase) من content/values.ts (واس N2642350).
 * - «المرساة» (anchor) هي الحقيقة الوحيدة في المشهد، ومصدرها في content/sources.ts:
 *   الشجاعة ← mofa-national-day · الرؤية ← spa-vision-2030 · الأصالة ← unesco-ich-sadu
 *   الهمّة ← spa-founding-day · الجود ← unesco-ich-sa · الكرم ← unesco-ich-coffee + unesco-ich-majlis
 *   (النصوص منقولة من research/_parts/timeline_facts.md و content/heritage.ts دون إضافة رقم أو تاريخ).
 * - ربط القيمة بالمحطة «قراءة المعرض» لا نصّ المصدر؛ لذا يُوسَم في الواجهة («قراءة المعرض») ولا يُنسب للمصدر.
 * - الأسطر الشعرية (cue) وعبارات التفاعل (action) نصوص المعرض نفسه، لا تحمل معلومة واقعية.
 */
export interface ValueScene extends Gated {
  id: Value['id']
  word: string
  /** «عزّنا بشجاعتنا» — من values.ts */
  phrase: string
  /** سطر واحد يفتتح المشهد (شعري، بلا معلومة واقعية) */
  cue: string
  /** ما يفعله الزائر (بالسحب/الضغط) */
  action: string
  /** تسمية الزر البديل بلا سحب/استمرار (WCAG 2.5.7) */
  altLabel: string
  /** السطر الذي يتكشّف عند اكتمال التفاعل — مقتطف مباشر من المرساة */
  reveal: string
  /** قراءة المعرض: صلة القيمة بالمحطة (تفسير لا واقعة) */
  reading: string
  /** المرساة الموثّقة (تظهر في «الدلالة») */
  anchor: { title: string; dateLabel: string; text: string }
  /** صورة حقيقية مرخّصة تُعرض في طبقة «الدلالة» فقط (لا تمسّ فنّ المشهد الرمزي نفسه) */
  photoId?: string
  /** إن كان في المشهد جزء تصوّري يُوسَم ظاهرًا */
  creative?: { label: string; note: string }
  /** تنبيه عن الرسم نفسه (مثلًا: نمط مستوحى لا منقول) */
  disclaimer?: string
}

const word = (id: Value['id']) => values.find((v) => v.id === id)!

const scene = (
  id: Value['id'],
  o: Omit<ValueScene, 'id' | 'word' | 'phrase' | 'status'>,
): ValueScene => ({ id, word: word(id).word, phrase: word(id).phrase, status: 'verified', ...o })

