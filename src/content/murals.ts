/**
 * الجداريات: ثلاث عشرة لوحة معلومات مصمَّمة لهذا المعرض تحديدًا — نصوصها أصلية والصور حقيقية مرخّصة
 * من ويكيميديا كومنز (لا صور مؤلَّفة بالذكاء الاصطناعي)، لا صفحات منسوخة من عمل غيرنا.
 * كل رقم أو معلومة يحمل مصدره عبر SourceLine؛ رابط عميق #/mural/<id> يحمله رمز الـQR بجانب كل لوحة.
 */

/** لبنات نص اللوحة بترتيب العرض */
export type MuralBlock =
  | { t: 'h'; text: string } // عنوان فرعي
  | { t: 'p'; text: string } // فقرة
  | { t: 'li'; label: string; text: string } // بند بعنوان: «الانتماء: …»
  | { t: 'line'; text: string } // سطر قصير مستقل
  | { t: 'list'; items: string[] } // «تراث • تاريخ • عمارة»
  | { t: 'strong'; text: string } // جملة بارزة
  | { t: 'verse'; ref: string } // موضع آية قرآنية (غير مستخدَم في اللوحات الحالية؛ الجذور مخصَّصة للآيات)

export interface MuralVerse {
  surah: number
  ayah: number
  surahName: string
  text: string
  sha256: string
  quotedTokens: number
  sourceIds: string[]
}

/** تصحيح إملائي — غير مستخدَم في اللوحات الحالية (كانت لتدقيق نصوص منسوخة من صور) */
export interface MuralCorrection {
  printed: string
  shown: string
  where: string
}

export interface Mural extends Gated {
  id: string
  page: number
  /** عنوان اللوحة */
  title: string
  /** اسم اللوحة في شريط التنقل السريع */
  label: string
  /** نص اللوحة مسطَّحًا (لـTextView وتحدّي المستكشف) */
  paragraphs: string[]
  /** نص اللوحة مبنيًّا (عناوين/بنود) للعرض */
  blocks: MuralBlock[]
  /** القاعة الرقمية المرتبطة باللوحة (رابط QR يفتح اللوحة، وزرّها يقود إلى القاعة) */
  hallId?: HallId
  /** صورة اللوحة الكبيرة والمصغّرة (من سجل الصور المرخّصة content/photos.ts) */
  src: string
  thumb: string
  w: number
  h: number
  alt: string
  verse?: MuralVerse
  corrections?: MuralCorrection[]
}

const h = (text: string): MuralBlock => ({ t: 'h', text })
const p = (text: string): MuralBlock => ({ t: 'p', text })
const li = (label: string, text: string): MuralBlock => ({ t: 'li', label, text })
const strong = (text: string): MuralBlock => ({ t: 'strong', text })

interface Def {
  hallId?: HallId
  alt: string
  photoId: string
  blocks: MuralBlock[]
  sourceIds: string[]
}

