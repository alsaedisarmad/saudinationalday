/** النص المسطَّح للوحة */
export const flatten = (blocks: MuralBlock[]): string[] =>
  blocks.map((b) => (b.t === 'li' ? `${b.label}: ${b.text}` : b.t === 'list' ? b.items.join(' • ') : b.t === 'verse' ? b.ref : b.text))

export const murals: Mural[] = (indexJson.items as Array<{ id: string; page: number; title: string; label: string }>).map((it) => {
  const d = defs[it.id]
  const ph = photo(d.photoId)
  return {
    id: it.id,
    page: it.page,
    title: it.title,
    label: it.label,
    paragraphs: flatten(d.blocks),
    blocks: d.blocks,
    hallId: d.hallId,
    src: ph.src,
    thumb: ph.thumb,
    w: ph.w,
    h: ph.h,
    alt: d.alt,
    status: 'verified',
    sourceIds: d.sourceIds,
  }
})

export const muralById = (id: string) => murals.find((m) => m.id === id)
